package org.beesearch.app.data.gpx

import org.beesearch.app.domain.gpx.*
import org.junit.Assert.*
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.DataInputStream
import java.io.IOException
import java.io.OutputStream
import java.util.concurrent.CancellationException

class GpxCm1EncoderTest {
    private fun point(index: Int = 0, lat: String = "0", elevation: String? = null, time: String? = null) =
        GpxSample(index, GpxCanonicalValues.latitude(lat), GpxCanonicalValues.longitude("0"),
            GpxCanonicalValues.elevation(elevation), GpxCanonicalValues.time(time))
    private fun tree(points: List<GpxSample> = listOf(point()), metadata: GpxMetadata = GpxMetadata("fixture")) =
        GpxCanonicalDraft(metadata, listOf(GpxTrack(0, listOf(GpxSegment(0, points)))))
    private fun bytes(root: GpxCanonicalDraft): ByteArray = ByteArrayOutputStream().also {
        assertEquals(GpxCm1Encoder.size(root), GpxCm1Encoder.write(root, it))
        assertEquals(it.size().toLong(), GpxCm1Encoder.size(root))
    }.toByteArray()
    private fun different(a: GpxCanonicalDraft, b: GpxCanonicalDraft) = assertFalse(bytes(a).contentEquals(bytes(b)))

    @Test fun a01LiteralIndependentGoldenCm1() {
        // Hand calculation from Stage1B §8/§15, not generated by the encoder:
        // sample record 66 bytes; samples list 4+(7+66)=77; segment 8+(7+77)=92;
        // segments list 4+(7+92)=103; track 8+7+7+(7+103)=132;
        // tracks list 4+(7+132)=143; root 10+14+7+7+7+(7+143)=195; material=205.
        val literal = """
            424545475058434d0001
            00010100000003312e31
            0002010000000766697874757265
            00030000000000 00040000000000 00050000000000
            0006030000008f 00000001 00010200000084
            0001010000000130 00020000000000 00030000000000
            00040300000067 00000001 0001020000005c
            0001010000000130 0002030000004d 00000001 00010200000042
            0001010000000130 0002010000000130 0003010000000130
            00040000000000 00050000000000
            000601000000074d495353494e47
            00070000000000 00080000000000
        """.filterNot { it.isWhitespace() }
        val expected = literal.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
        assertEquals(205, expected.size)
        assertArrayEquals(expected, bytes(tree()))
        // Equivalent lexical zero reaches the very same independent byte oracle.
        assertArrayEquals(expected, bytes(tree(listOf(point(lat = "+000.000")))))
    }

    @Test fun b06ExactDecimalEquivalenceInCm1() {
        for (a in listOf("+056.1200", "056.120", "56.12"))
            assertArrayEquals(bytes(tree(listOf(point(lat = "56.12")))), bytes(tree(listOf(point(lat = a)))))
        for (a in listOf("-0", "+0.0", "000.000"))
            assertArrayEquals(bytes(tree()), bytes(tree(listOf(point(lat = a)))))
    }

    @Test fun c01ExactCoordinateDifferenceSurvivesEncoding() {
        different(tree(listOf(point(lat = "1.00000000000000000000001"))),
            tree(listOf(point(lat = "1.00000000000000000000002"))))
    }

    @Test fun a02C02C03PermutationAndReversalAreNotSorted() {
        fun ordered(vararg values: String) = tree(values.mapIndexed { i, value -> point(i, value) })
        different(ordered("1", "2", "3"), ordered("2", "1", "3"))
        different(ordered("1", "2", "3"), ordered("3", "2", "1"))
        val samples = firstSamples(fields(bytes(ordered("3", "1", "2")))).map(::record)
        assertEquals(listOf("3", "1", "2"), samples.map { it[1].text() })
        assertEquals(listOf("0", "1", "2"), samples.map { it[0].text() })
    }

    @Test fun a03C04SegmentBoundariesIncludingEmptyAreMaterial() {
        val single = tree(listOf(point(0, "1"), point(1, "2")))
        val split = GpxCanonicalDraft(GpxMetadata("fixture"), listOf(GpxTrack(0, listOf(
            GpxSegment(0, listOf(point(0, "1"))), GpxSegment(1, listOf(point(0, "2"))),
        ))))
        different(single, split)
        val empty = GpxCanonicalDraft(GpxMetadata("fixture"), listOf(GpxTrack(0, listOf(
            GpxSegment(0, emptyList()), GpxSegment(1, listOf(point())),
        ))))
        different(tree(), empty)
        different(GpxCanonicalDraft(GpxMetadata("fixture"), emptyList()),
            GpxCanonicalDraft(GpxMetadata("fixture"), listOf(GpxTrack(0, emptyList()))))
    }

    @Test fun a04C05TrackAndSegmentPermutationPreservesNewOrdinals() {
        fun track(i: Int, value: String) = GpxTrack(i, listOf(GpxSegment(0, listOf(point(lat = value)))))
        val a = GpxCanonicalDraft(GpxMetadata("fixture"), listOf(track(0, "1"), track(1, "2")))
        val b = GpxCanonicalDraft(GpxMetadata("fixture"), listOf(track(0, "2"), track(1, "1")))
        different(a, b)
        fun segments(first: String, second: String) = GpxCanonicalDraft(GpxMetadata("fixture"), listOf(
            GpxTrack(0, listOf(GpxSegment(0, listOf(point(lat = first))), GpxSegment(1, listOf(point(lat = second)))))))
        different(segments("1", "2"), segments("2", "1"))
    }

    @Test fun a05C06AllSupportedMetadataAndNullEmptyAreFramed() {
        val base = tree()
        for (m in listOf(GpxMetadata("different"), GpxMetadata("fixture", sourceName = ""),
            GpxMetadata("fixture", sourceDesc = "desc"), GpxMetadata("fixture", authorName = "author")))
            different(base, tree(metadata = m))
        different(tree(metadata = GpxMetadata("fixture", sourceName = "")),
            tree(metadata = GpxMetadata("fixture", sourceName = " ")))
        val namedTrack = base.copy(tracks = GpxFrozenList(listOf(base.tracks[0].copy(name = "track"))))
        different(base, namedTrack)
        different(base, base.copy(tracks = GpxFrozenList(listOf(base.tracks[0].copy(description = "desc")))))
        val root = fields(bytes(tree(metadata = GpxMetadata("creator", "name", "desc", "author"))))
        assertEquals(listOf("1.1", "creator", "name", "desc", "author"), root.take(5).map { it.text() })
    }

    @Test fun a06UnicodeIsUtf8NotUtf16LengthOrNfc() {
        val root = fields(bytes(tree(metadata = GpxMetadata("fixture", sourceName = "é😀"))))
        assertEquals(6, root[2].payload.size)
        assertArrayEquals(byteArrayOf(0xc3.toByte(), 0xa9.toByte(), 0xf0.toByte(), 0x9f.toByte(), 0x98.toByte(), 0x80.toByte()), root[2].payload)
        different(tree(metadata = GpxMetadata("fixture", sourceName = "é")),
            tree(metadata = GpxMetadata("fixture", sourceName = "e\u0301")))
    }

    @Test fun c08ElevationNullZeroAndValueAreDifferent() {
        val none = tree()
        val zero = tree(listOf(point(elevation = "0")))
        different(none, zero)
        different(zero, tree(listOf(point(elevation = "0.000000000000000001"))))
    }

    @Test fun a09C09D14TimeFieldsHaveRealProducerAndRawProvenance() {
        val a = tree(listOf(point(time = "1970-01-01T00:00:00.123456789Z")))
        val b = tree(listOf(point(time = "1970-01-01T01:00:00.123456789+01:00")))
        different(a, b)
        different(a, tree(listOf(point(time = "1970-01-01T00:00:01.123456789Z"))))
        val sample = record(firstSamples(fields(bytes(a))).single())
        assertEquals(listOf("1970-01-01T00:00:00.123456789Z", "UTC", "0", "123456789"), sample.drop(4).map { it.text() })
        for ((raw, status) in listOf("2000-01-01T00:00:00" to "NO_ZONE", "bad" to "UNSUPPORTED")) {
            val s = record(firstSamples(fields(bytes(tree(listOf(point(time = raw)))))).single())
            assertEquals(raw, s[4].text()); assertEquals(status, s[5].text())
            assertEquals(0, s[6].kind); assertEquals(0, s[7].kind)
        }
    }

    @Test fun h05MaterialRebuildIsStableWithoutIdentityOrPersistenceInputs() {
        // Two independently constructed value trees, not a claim about future restart/restore.
        assertArrayEquals(bytes(tree()), bytes(tree()))
        val root = fields(bytes(tree()))
        assertEquals((1..6).toList(), root.map { it.tag })
        val track = record(list(root[5]).single())
        assertEquals((1..4).toList(), track.map { it.tag })
        assertEquals(listOf(1, 2), record(list(track[3]).single()).map { it.tag })
        assertEquals((1..8).toList(), record(firstSamples(root).single()).map { it.tag })
        // The closed schema has no slot for profile provenance, UUID/Territory/path/time/presentation.
        assertFalse(String(bytes(tree()), Charsets.ISO_8859_1).contains("GPX_1_1_STAGE_1"))
    }

    @Test fun everySamplePrimitiveHasItsOwnFixedTagAndCanonicalSpelling() {
        val sample = GpxSample(0, GpxCanonicalValues.latitude("+001.2500"), GpxCanonicalValues.longitude("-002.500"),
            GpxCanonicalValues.elevation("0003.750"), GpxCanonicalValues.time("1969-12-31T23:59:59.000000001Z"))
        val encoded = record(firstSamples(fields(bytes(tree(listOf(sample))))).single())
        assertEquals((1..8).toList(), encoded.map { it.tag })
        assertEquals(listOf("0", "1.25", "-2.5", "3.75", "1969-12-31T23:59:59.000000001Z", "UTC", "-1", "1"),
            encoded.map { it.text() })
    }
    @Test fun checkedArithmeticProvesU32AndLongOverflowWithoutHugeAllocation() {
        val max = 0xffffffffL
        assertEquals(max - 1, GpxCm1Sizes.u32(max - 1))
        assertEquals(max, GpxCm1Sizes.u32(max))
        assertEquals(max + 7, GpxCm1Sizes.field(max))
        assertEquals(Long.MAX_VALUE, GpxCm1Sizes.add(Long.MAX_VALUE - 1, 1))
        assertEquals(Long.MAX_VALUE - 1, GpxCm1Sizes.multiply(Long.MAX_VALUE / 2, 2))
        for (value in listOf(-1L, max + 1)) assertThrows(GpxCm1Failure::class.java) { GpxCm1Sizes.u32(value) }
        assertThrows(GpxCm1Failure::class.java) { GpxCm1Sizes.field(max + 1) }
        assertThrows(GpxCm1Failure::class.java) { GpxCm1Sizes.add(Long.MAX_VALUE, 1) }
        assertThrows(GpxCm1Failure::class.java) { GpxCm1Sizes.multiply(Long.MAX_VALUE / 2 + 1, 2) }
        assertThrows(GpxCm1Failure::class.java) { GpxCm1Sizes.add(-1, 1) }
    }

    @Test fun directWritingDoesNotNeedCompleteCm1ArrayAndDoesNotOwnStream() {
        var written = 0L
        var closed = false
        val sink = object : OutputStream() {
            override fun write(value: Int) { written++ }
            override fun write(value: ByteArray, offset: Int, length: Int) { written += length }
            override fun close() { closed = true }
        }
        val root = tree((0 until 1000).map { point(it) })
        assertEquals(GpxCm1Encoder.size(root), GpxCm1Encoder.write(root, sink))
        assertEquals(written, GpxCm1Encoder.size(root))
        assertFalse(closed)
    }

    @Test fun cancellationAndOutputFailurePropagateNoSuccessfulReturn() {
        assertThrows(CancellationException::class.java) { GpxCm1Encoder.size(tree()) { throw CancellationException() } }
        val output = ByteArrayOutputStream()
        val marker = CancellationException("cancel")
        val caught = assertThrows(CancellationException::class.java) {
            GpxCm1Encoder.write(tree(), output) { if (output.size() > 20) throw marker }
        }
        assertSame(marker, caught)
        assertTrue(output.size() > 0) // Caller must discard partial comparison material.
        val io = IOException("test-sink")
        assertSame(io, assertThrows(IOException::class.java) {
            GpxCm1Encoder.write(tree(), object : OutputStream() { override fun write(value: Int) { throw io } })
        })
    }

    // Independent read-only framing auditor, not an encoder and never a golden producer.
    private data class Entry(val tag: Int, val kind: Int, val payload: ByteArray) {
        fun text(): String { assertEquals(1, kind); return String(payload, Charsets.UTF_8) }
    }
    private fun fields(material: ByteArray): List<Entry> {
        assertArrayEquals("BEEGPXCM".toByteArray(Charsets.US_ASCII), material.copyOfRange(0, 8))
        assertEquals(0, material[8].toInt()); assertEquals(1, material[9].toInt())
        return record(Entry(0, 2, material.copyOfRange(10, material.size)))
    }
    private fun record(entry: Entry): List<Entry> {
        assertEquals(2, entry.kind)
        val input = DataInputStream(ByteArrayInputStream(entry.payload))
        val fields = mutableListOf<Entry>()
        while (input.available() > 0) fields.add(readEntry(input))
        assertEquals(fields.map { it.tag }.sorted().distinct(), fields.map { it.tag })
        return fields
    }
    private fun list(entry: Entry): List<Entry> {
        assertEquals(3, entry.kind)
        val input = DataInputStream(ByteArrayInputStream(entry.payload))
        val count = input.readInt()
        assertTrue(count >= 0)
        val items = (0 until count).map { readEntry(input).also { assertEquals(1, it.tag); assertEquals(2, it.kind) } }
        assertEquals(0, input.available())
        return items
    }
    private fun readEntry(input: DataInputStream): Entry {
        val tag = input.readUnsignedShort()
        val kind = input.readUnsignedByte()
        val length = input.readInt().toLong() and 0xffffffffL
        assertTrue(length <= input.available())
        val bytes = ByteArray(length.toInt()).also { input.readFully(it) }
        if (kind == 0) assertEquals(0, bytes.size)
        return Entry(tag, kind, bytes)
    }
    private fun firstSamples(root: List<Entry>): List<Entry> = list(record(list(record(list(root[5]).first())[3]).first())[1])
}